#!/usr/bin/env node
// Issue #87: a hand-written knowledge/NEXT.md survives the step log.
//
//   N1 runtime_sandbox_end (the real door, a daemon of the run's own): a committed hand-written NEXT.md is
//      byte-identical afterwards, and the sandbox outcome is in knowledge/agent-state.json history
//   N2 agent_record_step on the same kind of project: the same two facts (no daemon needed)
//   N3 a project whose NEXT.md is the generated one, and one with none, still get it written as before
//
// The N1 half SKIPS LOUDLY when there is no trx64-daemon binary. Nothing here touches :4312.
//   Locally:  C64RE_RUNTIME_BIN=<trx64-daemon> npm run e2e:issue87-next-md
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { Harness, ROOT, findDaemon, loopPrg, makeChecker } from "./lib/e2e-906-harness.mjs";

if (!existsSync(join(ROOT, "dist/server.js"))) { console.error("dist missing — run `npm run build:mcp`"); process.exit(2); }

const T = makeChecker("e2e-issue87-next-md");
const { check, head } = T;
const H = new Harness("c64re-i87-");
process.env.C64RE_STATE_DIR = H.state;

const FOOTER = "_Auto-generated by agent-workflow tools.";
const HAND = "# NEXT\n\nClosed on 2026-10-15. Release commit abc1234.\n\n## Open items\n- none\r\n";
const nextMd = (p) => join(p, "knowledge", "NEXT.md");
const generatedMd = (p) => join(p, "knowledge", "NEXT.generated.md");
const read = (p) => (existsSync(p) ? readFileSync(p) : undefined);
const stepLog = (p) => { try { return JSON.parse(readFileSync(join(p, "knowledge", "agent-state.json"), "utf8")).history.map((h) => h.step).join("\n"); } catch { return ""; } };

// ═══════════════════════════════════════════════════════════════════════════════════════════════
head("N1  runtime_sandbox_start + runtime_sandbox_end on a project with a hand-written NEXT.md");
const DAEMON = await findDaemon();
if (!DAEMON) {
  console.log("  SKIPPED  no trx64-daemon binary (set C64RE_RUNTIME_BIN). Skipped, NOT passed; N2 covers the same writer.");
} else {
  process.env.C64RE_RUNTIME_BIN = DAEMON;
  const proj = await H.project("hand-sandbox");
  writeFileSync(join(proj, "a.prg"), loopPrg());
  writeFileSync(nextMd(proj), HAND);
  const before = read(nextMd(proj));
  const mcp = await H.mcp(proj, { env: { C64RE_RUNTIME_BIN: DAEMON } });
  const started = await mcp.call("runtime_sandbox_start", { purpose: "issue 87", budget_minutes: 5, media_path: "a.prg" });
  const id = /\bsb-[a-z0-9-]+\b/.exec(started)?.[0];
  check(!!id, "a sandbox session starts", started.slice(0, 300));
  const ended = await mcp.call("runtime_sandbox_end", { session_id: id, outcome: "reached", summary: "issue87 summary" });
  check(/ended: reached/.test(ended), "it ends with outcome reached", ended.slice(0, 300));
  check(Buffer.compare(read(nextMd(proj)), before) === 0, "criterion 1: the hand-written NEXT.md is byte-identical", String(read(nextMd(proj))).slice(0, 300));
  check(stepLog(proj).includes(`Sandbox session ${id} ended (reached)`) && stepLog(proj).includes("issue87 summary"), "criterion 2: the outcome is in agent-state.json history", stepLog(proj));
  check(String(read(generatedMd(proj)) ?? "").includes(`Sandbox session ${id} ended (reached)`), "…and the generated state is kept beside it in NEXT.generated.md");
  mcp.stop();
}

// ═══════════════════════════════════════════════════════════════════════════════════════════════
head("N2  agent_record_step on a project with a hand-written NEXT.md");
{
  const proj = await H.project("hand-step");
  writeFileSync(nextMd(proj), HAND);
  const before = read(nextMd(proj));
  const mcp = await H.mcp(proj, { endpoint: "ws://127.0.0.1:9" });
  const out = await mcp.call("agent_record_step", { step: "issue87 step", next_action: "go on" });
  check(/Step recorded/.test(out), "agent_record_step records", out.slice(0, 300));
  await mcp.call("agent_set_role", { role: "analyst" });
  check(Buffer.compare(read(nextMd(proj)), before) === 0, "the hand-written NEXT.md is byte-identical after agent_record_step + agent_set_role", String(read(nextMd(proj))).slice(0, 300));
  check(stepLog(proj).includes("issue87 step"), "the step is in agent-state.json history", stepLog(proj));
  const gen = String(read(generatedMd(proj)) ?? "");
  check(gen.includes("issue87 step") && gen.includes(FOOTER), "the generated state is in NEXT.generated.md", gen.slice(0, 300));
  check(out.includes(generatedMd(proj)), "the tool's answer names the file it wrote", out);
  mcp.stop();
}

// ═══════════════════════════════════════════════════════════════════════════════════════════════
head("N3  criterion 3: a generated NEXT.md, or none, is still written as before");
{
  const proj = await H.project("generated");
  const mcp = await H.mcp(proj, { endpoint: "ws://127.0.0.1:9" });
  await mcp.call("agent_record_step", { step: "first step" });
  const first = String(read(nextMd(proj)) ?? "");
  check(first.includes("first step") && first.includes(FOOTER), "no NEXT.md: it is created, generated", first.slice(0, 300));
  await mcp.call("agent_record_step", { step: "second step" });
  const second = String(read(nextMd(proj)) ?? "");
  check(second.includes("second step") && second.includes(FOOTER), "a generated NEXT.md is rewritten with the new step", second.slice(0, 300));
  check(!existsSync(generatedMd(proj)), "…and no NEXT.generated.md appears");
  mcp.stop();
}

process.exit(T.done());
