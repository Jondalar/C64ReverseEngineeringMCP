#!/usr/bin/env node
// One address rule — proved to be one, not three.
//
// The rule ("an address is HEX; a JSON number is taken as-is") has been written down
// twice and has drifted twice. First between `entry_points` and the relocation loader,
// which read one notation two ways. Then again when a new door was written against the
// STATEMENT of the rule instead of against the function, while the pipeline half kept
// four inline `parseInt(x, 16)` sites of its own.
//
// So the rule now lives in exactly one body of code, `src/shared/address-rule.ts`, and
// this gate is what keeps it that way. Three checks:
//
//   1 the CommonJS twin (`pipeline/src/lib/address-rule.ts`) is generated from that
//     body and is byte-identical to it — `--write` regenerates it;
//   2 the two COMPILED modules answer identically over a corpus of inputs, values and
//     refusal messages alike, so a drift that survives (1) still cannot survive this;
//   3 no third copy: no other file re-states the rule, and no door in the disassembly
//     family parses an address or a count with an inline `parseInt` of its own.
//
// Hermetic: reads source, and imports dist/. Exit 0 = pass.
//   npm run check:address-rule            (check)
//   npm run check:address-rule -- --write (regenerate the twin)

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, relative } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const WRITE = process.argv.includes("--write");
const CANONICAL = join(ROOT, "src/shared/address-rule.ts");
const TWIN = join(ROOT, "pipeline/src/lib/address-rule.ts");
const BEGIN = "// ── shared body begins (generated into pipeline/src/lib/address-rule.ts) ──";
const END = "// ── shared body ends ──";

let pass = 0, fail = 0;
const check = (cond, msg, detail = "") => {
  if (cond) pass += 1; else fail += 1;
  console.log(`  ${cond ? "PASS" : "FAIL"}  ${msg}${detail ? `  (${detail})` : ""}`);
};

const TWIN_HEADER = [
  "// GENERATED from src/shared/address-rule.ts — DO NOT EDIT THIS FILE.",
  "//",
  "// `src/` is ESM and `pipeline/src/` is CommonJS and the two halves cannot import each",
  "// other's modules, so the one rule is compiled twice from one body. Everything below is",
  "// copied verbatim from the canonical file; `npm run check:address-rule -- --write`",
  "// regenerates it and the gate refuses a build where the two have drifted — by text and",
  "// by answer, over a corpus run through both compiled modules.",
  END,
  "",
].join("\n");

console.log("One address rule\n");

// ── 1 the twin is the same body ──────────────────────────────────────────────
console.log("── 1 one body, compiled twice");
const canonical = readFileSync(CANONICAL, "utf8");
const from = canonical.indexOf(BEGIN);
const to = canonical.indexOf(END);
if (from < 0 || to < 0) {
  check(false, "the canonical file carries its body markers", `${BEGIN} … ${END}`);
} else {
  const body = canonical.slice(from + BEGIN.length, to).replace(/^\n+/, "");
  const want = `${TWIN_HEADER}\n${body}${END}\n`;
  if (WRITE) {
    writeFileSync(TWIN, want, "utf8");
    console.log(`  WROTE ${relative(ROOT, TWIN)}`);
  }
  const have = existsSync(TWIN) ? readFileSync(TWIN, "utf8") : "";
  check(have === want,
    "pipeline/src/lib/address-rule.ts is the canonical body verbatim",
    have === want ? `${body.split("\n").length} lines` : "run: npm run check:address-rule -- --write");
}

// ── 2 the two compiled modules answer identically ────────────────────────────
console.log("\n── 2 the two compiled halves answer the same");
const esmPath = join(ROOT, "dist/shared/address-rule.js");
const cjsPath = join(ROOT, "dist/pipeline/lib/address-rule.cjs");
if (!existsSync(esmPath) || !existsSync(cjsPath)) {
  check(false, "both halves are built", `missing ${!existsSync(esmPath) ? esmPath : cjsPath} — run npm run build`);
} else {
  const esm = await import(pathToFileURL(esmPath).href);
  const cjs = createRequire(import.meta.url)(cjsPath);
  check(esm.ADDRESS_RULE === cjs.ADDRESS_RULE, "…and state the same rule", esm.ADDRESS_RULE.slice(0, 40));

  // Everything a caller has actually typed at these fields, plus the shapes that
  // decided the two earlier drifts.
  const CORPUS = [
    "E800", "$E800", "0xE800", "e800", "2000", "33", "78", "0x33", "$78", "100", "0",
    "  C000  ", "FFFF", "10000", "", "-1", "1.5", "$", "0x", "abcg", "analysis/x_analysis.json",
    0, 1, 33, 100, 0x2000, 65535, 65536, -1, 1.5, Number.NaN,
    null, undefined, true, [], {},
  ];
  const run = (fn, value) => {
    try { return `= ${fn(value, "f")}`; } catch (e) { return `! ${e.message}`; }
  };
  const diffs = [];
  for (const value of CORPUS) {
    for (const name of ["parseAddress", "parseCount"]) {
      const a = run(esm[name], value), b = run(cjs[name], value);
      if (a !== b) diffs.push(`${name}(${JSON.stringify(value) ?? String(value)}): ESM ${a} vs CJS ${b}`);
    }
    if (typeof value === "string") {
      const a = run((v, f) => esm.parseAddressList(v, f).join("/"), value);
      const b = run((v, f) => cjs.parseAddressList(v, f).join("/"), value);
      if (a !== b) diffs.push(`parseAddressList(${JSON.stringify(value)}): ESM ${a} vs CJS ${b}`);
      if (esm.looksLikeAddressList(value) !== cjs.looksLikeAddressList(value)) {
        diffs.push(`looksLikeAddressList(${JSON.stringify(value)}) disagrees`);
      }
    }
  }
  check(diffs.length === 0, `${CORPUS.length} inputs answer identically in both halves`, diffs.slice(0, 3).join(" | ") || "no divergence");

  // The rule itself, held to what it says. A regression here is the original bug.
  check(esm.parseCount("100", "f") === 256 && esm.parseCount(100, "f") === 100,
    'a string is hex and a number is taken as given ("100" = 256, 100 = 100)');
  check(esm.parseAddress("E800", "f") === 0xe800 && esm.parseAddress("$E800", "f") === 0xe800
    && esm.parseAddress("0xE800", "f") === 0xe800,
    '"E800", "$E800" and "0xE800" are one address');
  check(esm.parseAddress("2000", "f") === 0x2000, '"2000" is $2000, never decimal 2000');
  check(run(esm.parseAddress, "analysis/x.json").startsWith("! f:"),
    "a path in an address field is refused by field name, not turned into NaN",
    run(esm.parseAddress, "analysis/x.json").slice(0, 60));
}

// ── 3 no third copy ──────────────────────────────────────────────────────────
console.log("\n── 3 no third copy");
const RULE_TEXT = "an address is HEX";
const SOURCES = [
  "src/server-tools/analysis-workflow.ts",
  "src/lib/prg-workflow.ts",
  "pipeline/src/cli.ts",
  "pipeline/src/lib/prg-disasm.ts",
  "pipeline/src/lib/annotations.ts",
];
{
  const restated = [];
  for (const rel of SOURCES) {
    const path = join(ROOT, rel);
    if (!existsSync(path)) continue;
    const text = readFileSync(path, "utf8");
    // A quoted re-statement of the rule. Referring to it in a comment is fine; putting
    // it back in a string literal is how the second copy was born.
    for (const [index, line] of text.split("\n").entries()) {
      if (!line.includes(RULE_TEXT)) continue;
      if (/^\s*(\/\/|\*|\/\*)/.test(line)) continue;
      restated.push(`${rel}:${index + 1}`);
    }
  }
  check(restated.length === 0,
    "no door re-states the rule in a string of its own — they import ADDRESS_RULE",
    restated.join(", ") || "none");
}
{
  // An inline parse of an address or a count inside the disassembly family. Anything
  // that names one of these fields and reaches for parseInt/Number is a fourth copy
  // in the making; it must call parseAddress / parseCount / parseAddressList.
  const FIELD = /addr|offset|length|entry|reloc|seed|load/i;
  const PARSE = /(?:Number\.)?parseInt\s*\(|(?:^|[^.\w])Number\s*\(/;
  const inline = [];
  for (const rel of SOURCES) {
    const path = join(ROOT, rel);
    if (!existsSync(path)) continue;
    for (const [index, line] of readFileSync(path, "utf8").split("\n").entries()) {
      if (/^\s*(\/\/|\*|\/\*)/.test(line)) continue;
      if (!PARSE.test(line) || !FIELD.test(line)) continue;
      inline.push(`${rel}:${index + 1}  ${line.trim().slice(0, 90)}`);
    }
  }
  check(inline.length === 0,
    "no door parses an address or a count with a parseInt of its own",
    inline.join("\n        ") || "none");
}

console.log(`\n${fail ? "RED" : "GREEN"}  check-address-rule: ${pass} pass, ${fail} fail.`);
process.exit(fail ? 1 : 0);
