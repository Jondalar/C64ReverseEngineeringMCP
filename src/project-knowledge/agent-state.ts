// The step log of a project (knowledge/agent-state.json and the generated knowledge/NEXT.md): its shape, its reads and
// writes, and `recordAgentStepFromCode`. Its own module so that code which is not a tool call (the end of a sandbox) can
// add a step without loading the tool registrations, which reach the shared runtime backend.
import { existsSync, mkdirSync, readFileSync, renameSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { z } from "zod";
import { ProjectKnowledgeService } from "./service.js";

const AGENT_STATE_SCHEMA_VERSION = 1;

export const AgentRoleSchema = z.enum(["analyst", "cartographer", "implementer", "archivist", "cracker", "unset"]);
export type AgentRole = z.infer<typeof AgentRoleSchema>;

// Spec 917 D3 - the second axis beside the domain role: whether this session is the architect. Workers are
// subagents of the same server, so a stored "worker" would overwrite the architect's position; a worker carries
// no position and names its card in every report instead. A state written with the old "worker" reads as unset.
export const AgentPositionSchema = z.enum(["architect", "unset"]);
const StoredPositionSchema = z.preprocess((v) => (v === "worker" ? "unset" : v), AgentPositionSchema);
export type AgentPosition = z.infer<typeof AgentPositionSchema>;

const AgentHistoryEntrySchema = z.object({
  at: z.string().min(1),
  role: AgentRoleSchema,
  step: z.string().min(1),
  note: z.string().optional(),
});

export const AgentStateSchema = z.object({
  schemaVersion: z.literal(AGENT_STATE_SCHEMA_VERSION),
  updatedAt: z.string().min(1),
  role: AgentRoleSchema.default("unset"),
  position: StoredPositionSchema.default("unset"),
  currentFocus: z.string().optional(),
  lastCompletedStep: z.string().optional(),
  nextAction: z.string().optional(),
  constraints: z.array(z.string()).default([]),
  history: z.array(AgentHistoryEntrySchema).default([]),
});
export type AgentState = z.infer<typeof AgentStateSchema>;

export const HISTORY_LIMIT = 25;
export const HISTORY_RENDERED = 10;

export function nowIso(): string {
  return new Date().toISOString();
}

function emptyState(): AgentState {
  return {
    schemaVersion: AGENT_STATE_SCHEMA_VERSION,
    updatedAt: nowIso(),
    role: "unset",
    position: "unset",
    constraints: [],
    history: [],
  };
}

export function agentStatePath(projectRoot: string): string {
  return join(projectRoot, "knowledge", "agent-state.json");
}

export function nextMdPath(projectRoot: string): string {
  return join(projectRoot, "knowledge", "NEXT.md");
}

export function loadAgentState(projectRoot: string): AgentState {
  const path = agentStatePath(projectRoot);
  if (!existsSync(path)) return emptyState();
  try {
    const raw = JSON.parse(readFileSync(path, "utf8"));
    return AgentStateSchema.parse(raw);
  } catch {
    return emptyState();
  }
}

function writeAtomic(path: string, body: string): void {
  mkdirSync(dirname(path), { recursive: true });
  const tmp = `${path}.tmp`;
  writeFileSync(tmp, body, "utf8");
  renameSync(tmp, path);
}

function saveAgentState(projectRoot: string, state: AgentState): void {
  const path = agentStatePath(projectRoot);
  writeAtomic(path, `${JSON.stringify(state, null, 2)}\n`);
}

/** The last line renderNextMd emits; its presence marks a NEXT.md as ours to rewrite. */
export const NEXT_MD_GENERATED_FOOTER =
  "_Auto-generated by agent-workflow tools. Re-run agent_record_step / agent_set_role to update._";

function renderNextMd(projectRoot: string, projectName: string, state: AgentState): string {
  const lines: string[] = [];
  lines.push(`# NEXT — ${projectName}`);
  lines.push(``);
  lines.push(`_Updated: ${state.updatedAt}_`);
  lines.push(``);
  lines.push(`## Role`);
  lines.push(state.role);
  lines.push(``);
  if (state.position !== "unset") {
    lines.push(`## Position`);
    lines.push(state.position);
    lines.push(``);
  }
  lines.push(`## Current Focus`);
  lines.push(state.currentFocus?.trim() ? state.currentFocus : "_(not set)_");
  lines.push(``);
  lines.push(`## Last Completed Step`);
  lines.push(state.lastCompletedStep?.trim() ? state.lastCompletedStep : "_(none yet)_");
  lines.push(``);
  lines.push(`## Next Action`);
  lines.push(state.nextAction?.trim() ? state.nextAction : "_(propose via agent_propose_next)_");
  lines.push(``);
  lines.push(`## Constraints`);
  if (state.constraints.length === 0) {
    lines.push("_(none)_");
  } else {
    for (const c of state.constraints) lines.push(`- ${c}`);
  }
  lines.push(``);
  lines.push(`## History (most recent ${HISTORY_RENDERED})`);
  if (state.history.length === 0) {
    lines.push("_(empty)_");
  } else {
    const recent = state.history.slice(-HISTORY_RENDERED).reverse();
    for (const h of recent) {
      const noteSuffix = h.note ? ` — ${h.note}` : "";
      lines.push(`- ${h.at} [${h.role}] ${h.step}${noteSuffix}`);
    }
  }
  lines.push(``);
  lines.push(`---`);
  lines.push(NEXT_MD_GENERATED_FOOTER);
  void projectRoot;
  return lines.join("\n") + "\n";
}

/** True when knowledge/NEXT.md is absent or carries our generated footer; a hand-written file is never touched. */
function nextMdIsOurs(projectRoot: string): boolean {
  const path = nextMdPath(projectRoot);
  if (!existsSync(path)) return true;
  try {
    return readFileSync(path, "utf8").includes(NEXT_MD_GENERATED_FOOTER);
  } catch {
    return false;
  }
}

export function persistState(projectRoot: string, projectName: string, state: AgentState): AgentState & { nextMdKept: boolean } {
  const updated: AgentState = { ...state, updatedAt: nowIso() };
  saveAgentState(projectRoot, updated);
  const nextMdKept = !nextMdIsOurs(projectRoot);
  if (!nextMdKept) writeAtomic(nextMdPath(projectRoot), renderNextMd(projectRoot, projectName, updated));
  return { ...updated, nextMdKept };
}

/**
 * Spec 906 — add one entry to a project's step log from code, in the shape `agent_record_step` writes
 * (history entry with the current role, `lastCompletedStep`; NEXT.md regenerated only if missing or generated). Used when something
 * that is not a tool call ends — a sandbox session on its budget, its idle limit, its owner's death —
 * and its outcome belongs in the project's record. Throws when the directory is not a project; the
 * caller decides whether that matters.
 */
export function recordAgentStepFromCode(projectRoot: string, step: string, note?: string): void {
  const service = new ProjectKnowledgeService(projectRoot);
  const project = service.getProjectStatus().project;
  const prev = loadAgentState(projectRoot);
  const history = [...prev.history, { at: nowIso(), role: prev.role, step, ...(note ? { note } : {}) }].slice(-HISTORY_LIMIT);
  persistState(projectRoot, project.name, { ...prev, lastCompletedStep: step, history });
}
